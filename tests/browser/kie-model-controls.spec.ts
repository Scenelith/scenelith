import { readFileSync } from "node:fs";
import path from "node:path";
import { build } from "esbuild";
import { expect, test } from "@playwright/test";

test("model switching changes real generator inputs, quality and duration controls", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  const fixture = (await build({ entryPoints: ["tests/browser/fixtures/kie-model-controls.tsx"], absWorkingDir: process.cwd(), tsconfig: path.resolve("tsconfig.json"), bundle: true, write: false, platform: "browser", jsx: "automatic", define: { "process.env.NODE_ENV": '"production"' } })).outputFiles[0].text;
  await page.setContent(`<style>${readFileSync("node_modules/@xyflow/react/dist/style.css", "utf8")}${readFileSync("src/app/globals.css", "utf8")}${readFileSync("src/app/theme.css", "utf8")}</style><div id="root"></div>`);
  await page.addScriptTag({ content: fixture });
  const card = page.locator(".frame-node--generator");
  await card.hover();
  await expect(card.getByRole("button", { name: "IMAGE MODELS", exact: true })).toBeVisible();
  await card.getByRole("button", { name: "QUALITY", exact: true }).click();
  await page.keyboard.press("End");
  await page.keyboard.press("Enter");
  await expect(card.getByRole("button", { name: "QUALITY", exact: true })).toBeFocused();
  await card.getByRole("button", { name: "RATIO", exact: true }).click();
  await expect(page.getByRole("button", { name: "27:16", exact: true })).toHaveCount(0);
  await page.getByRole("button", { name: "1:1", exact: true }).click();
  await card.locator('.generator-assistant-trigger').click();
  await expect(page.getByRole('dialog',{name:'Prompt assistant',exact:true})).toBeVisible();
  await expect(card.locator('.generator-node-controls')).toHaveCSS('visibility','hidden');
  await page.getByRole('button',{name:'Assistant model',exact:true}).click();
  await page.getByRole('button',{name:/Qwen 3.7 Flash/}).click();
  await expect(page.getByRole('dialog',{name:'Prompt assistant',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Assistant model',exact:true})).toHaveText(/Qwen 3.7 Flash/);
  await page.getByRole('button',{name:'Close assistant',exact:true}).click();
  await page.getByRole("button", { name: "PixVerse", exact: true }).click();
  await card.hover();
  await expect(card.getByRole("button", { name: "DURATION", exact: true })).toBeVisible();
  await card.getByRole("button", { name: "QUALITY", exact: true }).click();
  await expect(page.getByRole("button", { name: "540P", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "540P", exact: true }).click();
  await card.getByRole("button", { name: "VIDEO MODELS", exact: true }).click();
  await page.getByRole("button", { name: /PixVerse V6 · Transition/ }).click();
  await expect(card.getByRole("button", { name: "RATIO", exact: true })).toHaveCount(0);
  await expect(card.locator(".generator-run")).toBeDisabled();
  await expect(card.getByText("Start frame", { exact: true }).first()).toBeVisible();
  await expect(card.getByText("End frame", { exact: true }).first()).toBeVisible();
  await page.getByRole("button", { name: "Omni", exact: true }).click();
  await card.hover();
  await expect(card.getByRole("button", { name: "DURATION", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Toggle video reference", exact: true }).click();
  await card.hover();
  await expect(card.getByRole("button", { name: "DURATION", exact: true })).toHaveCount(0);
  await expect(card.getByText("Auto duration", { exact: true })).toBeVisible();
  await expect(card.locator(".generator-sound-control")).toHaveCount(0);
  await expect(card.locator(".generator-credit-tooltip")).toContainText("168");
  await page.getByRole("button", { name: "Toggle video reference", exact: true }).click();
  await card.hover();
  await expect(card.getByRole("button", { name: "DURATION", exact: true })).toBeVisible();
  await page.getByRole("button",{name:"FLUX",exact:true}).click();
  await card.hover();
  await expect(card.getByRole("button",{name:"IMAGE MODELS",exact:true})).toHaveText("FLUX 3 Klein");
  await card.getByRole("button",{name:"RATIO",exact:true}).click();
  await expect(page.getByRole("button",{name:"9:21",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"9:21",exact:true}).click();
  await page.getByRole("button",{name:"Wan",exact:true}).click();
  await page.getByRole("button",{name:"Toggle video reference",exact:true}).click();
  await card.hover();
  await expect(card.getByRole("button",{name:"DURATION",exact:true})).toHaveText("5s");
  await card.getByRole("button",{name:"DURATION",exact:true}).click();
  await page.getByRole("button",{name:"12s",exact:true}).click();
  await expect(card.getByRole("button",{name:"DURATION",exact:true})).toHaveText("12s");
  await page.getByRole("button",{name:"Long video",exact:true}).click();
  await card.hover();
  await card.getByRole("button",{name:"DURATION",exact:true}).click();
  await page.getByRole("button",{name:/From reference/}).click();
  await expect(card.getByRole("button",{name:"DURATION",exact:true})).toHaveText("15s");
  await expect(card.locator(".generator-run")).toBeEnabled();
  await page.screenshot({path:"/tmp/flux3-wan-controls.png"});
  await page.getByRole("button", {name:"Kling",exact:true}).click();
  await card.hover();
  await expect(card.getByRole("button",{name:"VIDEO MODELS",exact:true})).toHaveText("Kling 4.0 · References");
  await card.getByRole("button",{name:"DURATION",exact:true}).click();
  await expect(page.getByRole("button",{name:"30s",exact:true})).toBeVisible();
  await page.getByRole("button",{name:"10s",exact:true}).click();
  await page.getByRole("button",{name:"Toggle video reference",exact:true}).click();
  await card.hover();
  await page.getByRole("button",{name:"Mention video",exact:true}).click();
  await card.hover();
  await expect(card.locator(".generator-credit-tooltip")).toContainText("570");
  await expect(card.locator(".generator-run")).toBeEnabled();
  await expect(card.locator(".generator-sound-control")).toHaveCount(0);
  await page.getByRole("button", {name:"Keyframes",exact:true}).click();
  await card.hover();
  await expect(card.getByText("Middle keyframes · chronological",{exact:true}).first()).toBeVisible();
  await expect(card.getByText("End frame",{exact:true}).first()).toBeVisible();
  await page.screenshot({path:"/tmp/kling4-controls.png"});
  expect(errors).toEqual([]);
});
